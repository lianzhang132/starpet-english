"""Mechanically export authored Python curriculum for the ArkTS offline client."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root / "server"))
from app.curriculum import LESSONS
from app.content import DIALOGUE_TRANSLATIONS, COURSE_WORLDS, DIALOGUES, WORDS, QUIZZES
from app.conversation import public_missions, CONVERSATION_MISSIONS, evaluate_answer

missions = public_missions()
voice_replies = set()
for mission in CONVERSATION_MISSIONS:
    for turn in mission['turns']:
        examples = ['', turn['question'], 'something unexpected']
        if turn['kind'] == 'name':
            examples += ['My name is Lily.']
        elif turn['kind'] == 'age':
            examples += [str(age) for age in range(4, 15)]
            examples += 'four five six seven eight nine ten eleven twelve thirteen fourteen'.split()
        else:
            examples += [variants[0] for variants in turn['choices'].values()]
        for example in examples:
            voice_replies.add(evaluate_answer(mission['id'], turn['id'], example)['reply'])
(root / 'server/app/static/voice-replies.json').write_text(json.dumps(sorted(voice_replies), ensure_ascii=False), encoding='utf-8')
(root / "server/app/static/conversations.mjs").write_text(
    '// Generated by tools/export-curriculum.py. Edit server/app/conversation.py.\nexport const CONVERSATION_MISSIONS = '
    + json.dumps(missions, ensure_ascii=False, indent=2) + ';\n', encoding="utf-8")
java_rows = ",\n".join(
    "        new PetMission(" + ", ".join(json.dumps(value, ensure_ascii=False) for value in
        [mission["id"], mission["turns"][0]["question"], mission["turns"][0]["hint"]]) + ")"
    for mission in missions)
(root / "android/app/src/main/java/com/starpet/english/compat/PetMission.java").write_text(
    '// Generated by tools/export-curriculum.py.\npackage com.starpet.english.compat;\n'
    + 'final class PetMission {\n'
    + '    final String id, question, hint;\n'
    + '    private PetMission(String id, String question, String hint) { this.id=id; this.question=question; this.hint=hint; }\n'
    + '    private static final PetMission[] ALL = {\n' + java_rows + '\n    };\n'
    + '    static int count() { return ALL.length; }\n'
    + '    static PetMission at(int index) { return ALL[Math.floorMod(index, ALL.length)]; }\n'
    + '    static int indexOf(String id) { if (id == null) return -1; for (int i = 0; i < ALL.length; i++) if (ALL[i].id.equals(id)) return i; return -1; }\n'
    + '    static int dueIndex(String id, long dueAt, long now) { return dueAt > 0 && dueAt <= now ? indexOf(id) : -1; }\n'
    + '    static boolean valid(String id) { return indexOf(id) >= 0; }\n'
    + '}\n', encoding="utf-8")

header = '''// Generated by tools/export-curriculum.py. Edit server/app/curriculum.py.
import { QuizItem } from './CourseData';
export interface LessonWord { word: string; meaning: string; emoji: string; }
export interface LessonContent { id: string; worldId: string; words: LessonWord[]; sentence: string; translation: string; questions: QuizItem[]; }
export const LESSONS: LessonContent[] = '''
(root / "entry/src/main/ets/data/LessonLibrary.ets").write_text(header + json.dumps(LESSONS, ensure_ascii=False, indent=2) + ';\n', encoding="utf-8")
print(f"Exported {len(LESSONS)} lessons, {sum(len(item['questions']) for item in LESSONS)} questions")
translations_header = '// Generated by tools/export-curriculum.py. Edit server/app/content.py.\n'
(root / "server/app/static/dialogues.mjs").write_text(
    translations_header + 'export const DIALOGUE_TRANSLATIONS = ' + json.dumps(DIALOGUE_TRANSLATIONS, ensure_ascii=False, indent=2) + ';\n', encoding="utf-8")
(root / "entry/src/main/ets/data/DialogueTranslations.ets").write_text(
    translations_header + 'export interface SceneTranslation { id: string; lines: string[]; }\n'
    + 'export const DIALOGUE_TRANSLATIONS: SceneTranslation[] = '
    + json.dumps([{"id": key, "lines": value} for key, value in DIALOGUE_TRANSLATIONS.items()], ensure_ascii=False, indent=2) + ';\n', encoding="utf-8")
catalog = {"worlds": COURSE_WORLDS, "words": WORDS, "quizzes": QUIZZES, "dialogues": DIALOGUES,
           "lessons": LESSONS, "conversations": public_missions()}
(root / "server/app/static/catalog.json").write_text(json.dumps(catalog, ensure_ascii=False), encoding="utf-8")
deployment = json.loads((root / "config/deployment.json").read_text(encoding="utf-8"))
(root / "server/app/static/server-config.mjs").write_text(
    '// Generated by tools/export-curriculum.py. Edit config/deployment.json.\nexport const API_ORIGIN = '
    + json.dumps(deployment['apiOrigin']) + ';\nexport const API_FALLBACK_ORIGIN = '
    + json.dumps(deployment.get('apiFallbackOrigin', '')) + ';\n', encoding="utf-8")

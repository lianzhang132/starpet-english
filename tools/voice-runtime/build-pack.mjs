import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { loadVoice, VOICE_MODEL } from './model.mjs';
import { pcm16Wav } from './wav.mjs';
import { ALPHABET, PHONICS_SOUNDS, CVC_BLENDS } from '../../server/app/static/phonics.mjs';
import { isChineseText } from '../../server/app/static/text-language.mjs';
import { VIDEO_LESSONS } from '../../server/app/static/videos/catalog.mjs';

const root=resolve(import.meta.dirname,'../../server/app/static');
const catalog=JSON.parse(await readFile(resolve(root,'catalog.json'),'utf8'));
const replies=JSON.parse(await readFile(resolve(root,'voice-replies.json'),'utf8'));
const texts=new Set();
const add=text=>{if(typeof text==='string'&&text.trim()&&!isChineseText(text))texts.add(text.trim().replace(/\s+/g,' '))};
catalog.words.forEach(word=>add(word.word));
catalog.quizzes.forEach(question=>question.answers.forEach(add));
catalog.lessons.forEach(lesson=>{lesson.words.forEach(word=>add(word.word));add(lesson.sentence);lesson.questions.forEach(question=>question.answers.forEach(add))});
catalog.dialogues.forEach(scene=>scene.lines.forEach(add));
catalog.conversations.forEach(scene=>scene.turns.forEach(turn=>add(turn.question)));
ALPHABET.forEach(item=>{add(item.letter);add(item.word)});
PHONICS_SOUNDS.forEach(item=>item.words.forEach(add));CVC_BLENDS.forEach(item=>add(item.word));replies.forEach(add);
add("Hello! I am Bobo. Let's speak English together!");
VIDEO_LESSONS.forEach(lesson=>{lesson.transcript.forEach(cue=>add(cue.en));lesson.questions.forEach(q=>q.options.forEach(o=>add(o.en)));lesson.practice.forEach(p=>add(p.en));(lesson.interactions||[]).forEach(p=>add(p.promptEn))});
['apple','dog','ball','milk','banana'].forEach(add);
const folder=resolve(root,'audio/en-us');await mkdir(folder,{recursive:true});
const hash=data=>createHash('sha256').update(data).digest('hex');
const signature=JSON.stringify(VOICE_MODEL),clips={};
let previous={};try{previous=JSON.parse(await readFile(resolve(root,'audio-manifest.json'),'utf8')).clips||{}}catch{}
const tts=await loadVoice();let index=0;
for(const text of [...texts].sort()){
  const name=hash(signature+'\n'+text)+'.wav',file=resolve(folder,name);
  let wav;try{const existing=await readFile(file);if(previous[text]?.sha256===hash(existing))wav=existing}catch{}
  if(!wav){const audio=await tts.generate(text,{voice:VOICE_MODEL.voice,speed:VOICE_MODEL.speed});wav=pcm16Wav(audio.audio,audio.sampling_rate);await writeFile(file,wav)}
  clips[text]={path:'/static/audio/en-us/'+name,durationMs:Math.round((wav.length-44)/48),sha256:hash(wav)};
  const manifest={format:1,...VOICE_MODEL,clips};
  // Persist after each clip so an interrupted build resumes without regenerating finished assets.
  await writeFile(resolve(root,'audio-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log(JSON.stringify({completed:++index,total:texts.size,text,durationMs:clips[text].durationMs}));
}
await writeFile(resolve(root,'audio-manifest.mjs'),'// Generated by tools/voice-runtime/build-pack.mjs\nexport const AUDIO_CLIPS = '+JSON.stringify(clips)+';\n');
console.log('Complete:',texts.size,'offline English clips');
